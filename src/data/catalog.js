/** Products sharing a category, then a fabric or metal, then an occasion. */
export function relatedTo(product, limit = 4) {
  if (!product) return [];
  const score = (p) => {
    let s = 0;
    if (p.category === product.category) s += 6;
    if (p.fabric && p.fabric === product.fabric) s += 3;
    if (p.metal && p.metal === product.metal) s += 3;
    s += (p.occasion || []).filter((o) => (product.occasion || []).includes(o)).length;
    if (Math.abs(p.price - product.price) < product.price * 0.4) s += 2;
    return s;
  };
  return PRODUCTS.filter((p) => p.slug !== product.slug)
    .sort((a, b) => score(b) - score(a) || b.rating - a.rating)
    .slice(0, limit);
}

/** Currency in the Indian grouping convention (1,24,500). */
export function formatINR(value) {
  return `₹${Math.round(value).toLocaleString('en-IN')}`;
}

