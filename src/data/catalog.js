/** Deterministic hash so stock levels stay stable across renders and reloads. */
function seeded(str, n) {
  let h = 2166136261;
  for (let i = 0; i < str.length; i += 1) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return Math.abs(h) % n;
}

export const PRODUCTS = RAW.map((p, i) => {
  const stock = p.limited ? 1 + seeded(p.slug, 2) : 3 + seeded(p.slug, 14);
  return {
    id: `CH-${String(1001 + i)}`,
    ...p,
    currency: 'INR',
    images: p.images.filter(Boolean),
    sizes: SIZES[p.category] || null,
    stock,
    inStock: stock > 0,
    care: CARE[p.category],
    isNew: (p.tags || []).includes('new-arrivals'),
    isBestSeller: (p.tags || []).includes('best-sellers'),
    onOffer: Boolean(p.compareAt),
    discount: p.compareAt ? Math.round(((p.compareAt - p.price) / p.compareAt) * 100) : 0,
    /* used by the "Newest" sort — a later index means an earlier arrival */
    addedAt: RAW.length - i,
  };
});

